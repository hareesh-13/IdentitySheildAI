# -*- coding: utf-8 -*-
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.application import MIMEApplication
from dotenv import load_dotenv
import os

def send_confirmation_email(report_data, pdf_path):
    """
    Sends a professional confirmation email to the user with the generated PDF attached.
    Will safely return False if SMTP is not configured.
    """
    # Always reload .env so credentials added after server start are picked up
    load_dotenv(override=True)
    
    sender_email = os.environ.get('MAIL_USERNAME', '').strip()
    sender_password = os.environ.get('MAIL_PASSWORD', '').strip()
    smtp_server = os.environ.get('MAIL_SERVER', 'smtp.gmail.com').strip()
    smtp_port = int(os.environ.get('MAIL_PORT', 587))
    
    recipient_email = report_data.get('email')
    
    if not sender_email or not sender_password:
        print("[EMAIL] Warning: MAIL_USERNAME or MAIL_PASSWORD not set in .env. Skipping email sending.")
        return False
        
    try:
        # Create message container
        msg = MIMEMultipart('mixed')
        msg['Subject'] = f"Incident Report Confirmation - {report_data.get('complaint_id')} - IdentityShield AI"
        msg['From'] = f"IdentityShield AI <{sender_email}>"
        msg['To'] = recipient_email
        
        # Create HTML Body
        html_content = f"""
        <html>
        <head>
            <style>
                body {{ font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; background-color: #f8fafc; color: #334155; margin: 0; padding: 20px; }}
                .container {{ max-width: 600px; margin: 0 auto; background-color: #ffffff; border-radius: 8px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0, 0, 0, 0.1); }}
                .header {{ background-color: #0ea5e9; padding: 25px; text-align: center; color: white; }}
                .header h2 {{ margin: 0; font-weight: 600; letter-spacing: 0.5px; }}
                .content {{ padding: 30px; line-height: 1.6; }}
                .content h3 {{ color: #0284c7; margin-top: 0; }}
                .details-box {{ background-color: #f1f5f9; border-left: 4px solid #0ea5e9; padding: 15px; margin: 20px 0; border-radius: 0 4px 4px 0; }}
                .details-box p {{ margin: 8px 0; font-size: 0.95em; }}
                .footer {{ background-color: #f8fafc; padding: 20px; text-align: center; font-size: 0.85em; color: #64748b; border-top: 1px solid #e2e8f0; }}
                .btn {{ display: inline-block; background-color: #0ea5e9; color: white; text-decoration: none; padding: 10px 20px; border-radius: 5px; font-weight: 600; margin-top: 15px; }}
            </style>
        </head>
        <body>
            <div class="container">
                <div class="header">
                    <h2>IdentityShield AI</h2>
                    <p style="margin: 5px 0 0 0; opacity: 0.9;">Incident Report Confirmation</p>
                </div>
                <div class="content">
                    <h3>Hello {report_data.get('name', 'User')},</h3>
                    <p>Thank you for submitting an incident report to IdentityShield AI. Your report has been successfully logged in our system.</p>
                    
                    <div class="details-box">
                        <p><strong>Tracking ID:</strong> {report_data.get('complaint_id')}</p>
                        <p><strong>Date & Time:</strong> {report_data.get('timestamp')}</p>
                        <p><strong>Incident Category:</strong> {report_data.get('incident_type')}</p>
                        <p><strong>Prediction Result:</strong> {"Deepfake Detected" if report_data.get('score') else "Manual Review Pending"}</p>
                        <p><strong>Confidence:</strong> {report_data.get('confidence', 'N/A')}{'%' if report_data.get('confidence') else ''}</p>
                    </div>
                    
                    <p><strong>Next Steps:</strong></p>
                    <p>Our security analysts will review your report within 24-48 hours. If the media is verified as a malicious deepfake or phishing attempt, it will be added to our global blacklist to protect the wider community.</p>
                    <p>Please find the official <strong>Complaint Report PDF</strong> attached to this email. It serves as your digital evidence receipt.</p>
                    
                    <p>Stay safe online,</p>
                    <p><em>The IdentityShield AI Team</em></p>
                </div>
                <div class="footer">
                    <p>This is an automated message generated by IdentityShield AI. Please do not reply directly to this email.</p>
                </div>
            </div>
        </body>
        </html>
        """
        
        # Attach HTML
        msg.attach(MIMEText(html_content, 'html'))
        
        # Attach PDF
        if os.path.exists(pdf_path):
            with open(pdf_path, 'rb') as f:
                pdf_attachment = MIMEApplication(f.read(), _subtype="pdf")
                pdf_attachment.add_header('Content-Disposition', 'attachment', filename=os.path.basename(pdf_path))
                msg.attach(pdf_attachment)
        else:
            print(f"[EMAIL] Warning: PDF file not found at {pdf_path}")
            
        # Send Email
        server = smtplib.SMTP(smtp_server, smtp_port)
        server.starttls()
        server.login(sender_email, sender_password)
        server.send_message(msg)
        server.quit()
        
        print(f"[EMAIL] Confirmation sent successfully to {recipient_email}")
        return True
        
    except Exception as e:
        print(f"[EMAIL] Error sending confirmation email: {e}")
        return False


